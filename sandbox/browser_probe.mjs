import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import fs from 'node:fs';
const dir='/output/game';
const log={build:false,loads:false,errors:[],checks:{},states:[],notes:[]};
fs.mkdirSync('/output/screenshots',{recursive:true});
const build=spawn('/opt/lab/node_modules/.bin/vite',['build','--configLoader','native'],{cwd:dir});
let text='';build.stdout.on('data',d=>text+=d);build.stderr.on('data',d=>text+=d);
await new Promise(resolve=>build.on('close',code=>{log.build=code===0;log.build_log=text;resolve();}));
if(!log.build){fs.writeFileSync('/output/browser_validation.json',JSON.stringify(log,null,2));process.exit(0);}
const server=spawn('/opt/lab/node_modules/.bin/vite',['--host','127.0.0.1','--port','4173','--strictPort','--configLoader','native'],{cwd:dir});
let browser;
try{
  await new Promise(r=>setTimeout(r,2500));
  browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1280,height:720}});
  page.on('pageerror',e=>log.errors.push(String(e)));
  page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:4173')&&!r.url().startsWith('data:')&&!r.url().startsWith('blob:'))log.errors.push('External request: '+r.url());});
  await page.goto('http://127.0.0.1:4173');await page.waitForTimeout(1000);
  log.loads=true;log.checks.canvas=await page.locator('canvas').count()>0;
  log.menu_text=await page.locator('body').innerText();
  await page.screenshot({path:'/output/screenshots/menu.png'});
  const snapshot=()=>page.evaluate(()=>{const h=window.__BENCHMARK__;return h?.snapshot?h.snapshot():null;});
  const before=await snapshot();log.states.push({label:'menu',value:before});
  const options=page.locator('select');if(await options.count())await options.first().selectOption({index:1});
  const car=page.getByRole('button',{name:/select|sport|rally|coupe|car/i});if(await car.count())await car.first().click();
  const start=page.getByRole('button',{name:/start|race|play/i});if(await start.count())await start.first().click();
  await page.waitForTimeout(4000);
  const race=await snapshot();log.states.push({label:'race',value:race});
  log.checks.selection=Boolean(before&&race&&before.selectedCar!==race.selectedCar);
  await page.keyboard.down('w');await page.waitForTimeout(3000);await page.keyboard.up('w');
  const moved=await snapshot();log.states.push({label:'moved',value:moved});
  log.checks.movement=Boolean(race&&moved&&JSON.stringify(race.playerPosition)!==JSON.stringify(moved.playerPosition));
  log.checks.timer=Boolean(race&&moved&&moved.elapsed>race.elapsed);
  log.checks.hud=(await page.locator('body').innerText()).match(/speed|lap|km\/h|position/i)!==null;
  await page.screenshot({path:'/output/screenshots/race_chase.png'});
  await page.keyboard.press('c');await page.waitForTimeout(300);const hood=await snapshot();
  log.checks.camera=Boolean(moved&&hood&&moved.camera!==hood.camera);
  await page.screenshot({path:'/output/screenshots/race_hood.png'});
  await page.keyboard.press('c');await page.waitForTimeout(300);await page.screenshot({path:'/output/screenshots/race_overhead.png'});
  await page.keyboard.press('p');const pause=await snapshot();await page.waitForTimeout(1000);const pause2=await snapshot();
  log.checks.pause=Boolean(pause&&pause2&&Math.abs(pause.elapsed-pause2.elapsed)<0.05);
  await page.keyboard.press('p');
  await page.evaluate(()=>window.__BENCHMARK__?.step?.(120,0.016));
  const sim=await snapshot();log.states.push({label:'simulation',value:sim});
  log.npc_observations=sim?.npcs??null;
  log.checks.npc_laps=Boolean(sim?.npcs?.length>=4&&sim.npcs.every(n=>n.laps>=1));
  await page.keyboard.press('r');await page.waitForTimeout(1000);const reset=await snapshot();
  log.checks.restart=Boolean(reset&&moved&&reset.elapsed<moved.elapsed);
  log.notes.push('Hooks are candidate supplied. Snapshot claims alone do not prove collisions, valid checkpoints, or NPC intelligence; these require manual review. No credit awarded for hooks alone.');
}catch(e){log.errors.push(String(e));}finally{if(browser)await browser.close();server.kill();}
fs.writeFileSync('/output/browser_validation.json',JSON.stringify(log,null,2));
console.log(JSON.stringify(log));
